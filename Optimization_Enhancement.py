"""Measure prompt-optimization impact against a synthetic holdout period."""

import json
import sys
from typing import Any

from financial_forecasting_common import (
    MODEL_CONFIG,
    call_model,
    make_sample_company_data,
    parse_json_object,
)


def baseline_forecast(training: list[dict[str, Any]], field: str, horizon: int) -> list[float]:
    """Use the latest observed value as a transparent naïve benchmark."""
    return [float(training[-1][field])] * horizon


def validate_forecast(result: dict[str, Any], horizon: int) -> list[dict[str, float]]:
    values = result.get("forecasts")
    if not isinstance(values, list) or len(values) != horizon:
        raise RuntimeError(f"Model must return exactly {horizon} forecast rows.")
    validated = []
    for row in values:
        if not isinstance(row, dict):
            raise RuntimeError("Each forecast row must be a JSON object.")
        clean = {}
        for field in ("revenue_usd", "support_tickets"):
            value = row.get(field)
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise RuntimeError(f"Forecast field {field} must be numeric.")
            clean[field] = float(value)
        validated.append(clean)
    return validated


def calculate_metrics(
    predictions: list[float], actuals: list[float]
) -> dict[str, float]:
    errors = [abs(predicted - actual) for predicted, actual in zip(predictions, actuals)]
    mape = [
        error / abs(actual) * 100
        for error, actual in zip(errors, actuals)
        if actual != 0
    ]
    return {
        "mae": round(sum(errors) / len(errors), 2),
        "mape_pct": round(sum(mape) / len(mape), 2) if mape else 0.0,
    }


def build_prompt(
    training: list[dict[str, Any]], horizon: int, optimized: bool
) -> str:
    method = (
        "OPTIMIZED: Treat the last row's month as the information cutoff; "
        "use only supplied training observations (no look-ahead). Check trend, "
        "seasonality, and recent level shifts. Forecast each month, preserve "
        "units, avoid false precision, and return exactly the required JSON."
        if optimized
        else "Review the historical data and predict the next six months."
    )
    return f"""{method}

Company context: hypothetical technology-support provider. Data is synthetic teaching data, not real company records. Predict monthly revenue_usd (US dollars) and support_tickets (count) for the {horizon} months immediately after the last training row. Do not include dates or explanatory prose inside the JSON.

Return exactly this structure:
{{"forecasts":[{{"revenue_usd":0.0,"support_tickets":0}}]}}

Training data:
{json.dumps(training, indent=2)}
"""


def run() -> int:
    try:
        data = make_sample_company_data(36)
        horizon = 6
        training, holdout = data[:-horizon], data[-horizon:]
        actuals = {
            "revenue_usd": [float(row["revenue_usd"]) for row in holdout],
            "support_tickets": [float(row["support_tickets"]) for row in holdout],
        }
        results: dict[str, Any] = {
            "company_context": "Synthetic hypothetical technology-support provider.",
            "methodology": {
                "training_months": len(training),
                "holdout_months": len(holdout),
                "optimized_prompt_changes": [
                    "explicit information cutoff and no-look-ahead requirement",
                    "company context and clear financial/operating units",
                    "requests trend, seasonality, and level-shift review",
                    "fixed JSON schema and exact forecast horizon",
                ],
                "note": (
                    "The holdout is generated by the same deterministic sample "
                    "process as training; its accuracy scores do not establish "
                    "performance on real businesses."
                ),
            },
            "actual_holdout": holdout,
            "models": {},
        }

        for key, config in MODEL_CONFIG.items():
            model_result: dict[str, Any] = {"model": config["model"], "prompts": {}}
            for approach in ("baseline_prompt", "optimized_prompt"):
                prompt = build_prompt(
                    training, horizon, optimized=approach == "optimized_prompt"
                )
                raw = call_model(
                    key,
                    "You are a careful financial forecaster. Never claim synthetic data is actual company performance.",
                    prompt,
                )
                forecasts = validate_forecast(parse_json_object(raw), horizon)
                scores = {
                    field: calculate_metrics(
                        [row[field] for row in forecasts], actuals[field]
                    )
                    for field in actuals
                }
                model_result["prompts"][approach] = {
                    "forecasts": forecasts,
                    "holdout_metrics": scores,
                }

            local_baseline = {
                field: calculate_metrics(
                    baseline_forecast(training, field, horizon), actuals[field]
                )
                for field in actuals
            }
            model_result["naive_last_value_baseline"] = local_baseline
            results["models"][key] = model_result

        results["interpretation"] = (
            "Compare optimized_prompt with baseline_prompt for each model and "
            "with naive_last_value_baseline. Lower MAE/MAPE is better. This is "
            "a small, synthetic holdout; real use requires rolling-origin tests, "
            "real data, and repeated periods."
        )
        with open("optimization_enhancement_results.json", "w", encoding="utf-8") as output:
            json.dump(results, output, indent=2)
        print("Saved optimization_enhancement_results.json")
        return 0
    except (RuntimeError, OSError, ValueError) as exc:
        print(f"Optimization evaluation failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(run())

